def generate(n: int) -> list[dict]:
    seen: set[str] = set()
    out: list[dict] = []
    attempts = 0
    while len(out) < n and attempts < n * 20:
        attempts += 1
        text = random.choice(TEMPLATES)()
        if text in seen:
            continue
        seen.add(text)
        out.append({"text": text, "topics": ["stereometry_generated"]})
    return out


def save_jsonl(items: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for it in items:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    items = generate(n=600)
    out_dir = Path(__file__).resolve().parent.parent / "data" / "raw"
    save_jsonl(items, out_dir / "generated_stereometry.jsonl")
    print(f"Сгенерировано задач по стереометрии: {len(items)}")
